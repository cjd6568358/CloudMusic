"""§61.361: tab 图标对齐（Search 放大 / More 加重）+ APP 图标唱片缩小。"""

# ---------- 1. tab icons ----------
p = 'app/src/main/kotlin/com/example/cloudmusic/ui/FnIcons.kt'
s = open(p, encoding='utf-8').read()

old_search = '''            FnIcon.Search -> {
                ring(11f, 11f, 6f)
                line(15.2f, 15.2f, 20f, 20f)
            }'''
new_search = '''            // §61.361（G-3 二次，用户「tab 图标奇奇怪怪的」）：真机四图标包围盒实测
            // Home 77×63 / Library 73×65 / Search **62×57** / More 75×19 —— 放大镜整整小一圈。
            // 原 ring(11,11,6)+柄到 20 = 16 单位；改为 ring(10.8,10.8,7.2)+柄到 20.9 = 18.3 单位，
            // 与 Home 的 18.4 同级，仍是标准放大镜语形（圆大柄短）。
            FnIcon.Search -> {
                ring(10.8f, 10.8f, 7.2f)
                line(15.9f, 15.9f, 20.9f, 20.9f)
            }'''
assert s.count(old_search) == 1, ('search', s.count(old_search))
s = s.replace(old_search, new_search)

old_more = '''            FnIcon.More -> {
                dot(4.4f, 12f, 2.4f)
                dot(12f, 12f, 2.4f)
                dot(19.6f, 12f, 2.4f)
            }'''
new_more = '''            // §61.361：原 r=2.4 实测包围盒只有 75×19、填充率 0.54 —— 同排并列时明显比
            // 另外三个「轻」，而且高度只有它们的三分之一。半径加到 2.9、两端外扩到 4.2/19.8，
            // 宽度 21.6 单位（≈82px）与 Home 的 77px 同级；仍是 more_horiz 三点语形，
            // 不改成 2×2 方格（A-4 已论证方格轮廓总长翻倍会反向失衡）。
            FnIcon.More -> {
                dot(4.2f, 12f, 2.9f)
                dot(12f, 12f, 2.9f)
                dot(19.8f, 12f, 2.9f)
            }'''
assert s.count(old_more) == 1, ('more', s.count(old_more))
s = s.replace(old_more, new_more)
open(p, 'w', encoding='utf-8', newline='').write(s)
print('FnIcons patched')

