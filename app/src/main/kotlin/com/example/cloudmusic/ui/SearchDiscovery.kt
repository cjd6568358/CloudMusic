/**
 * §61.326（A-3）搜索发现热词：**同一实体只出现一次**。
 *
 * 病根（评审 §六-5 / 真机 01:43 截图）：热词直接取 `groupingBy { it.artist }` 的原始字符串，
 * 而标签来自不同文件、不同抓取工具 —— `刘若英` / `劉若英` / `"刘若英` 会并列成三个胶囊，
 * 用户看到的是「别名垃圾」。字符串层面的差异有四种，归一必须逐层做：
 *
 *  1. **全角/兼容字形**：`ＡＢＣ`、`＂`、`（` —— NFKC 归一；
 *  2. **引号/括号/标点包裹**：`"刘若英`、`「刘若英」`、`刘若英.` —— 只剥**两端**，不动中间；
 *  3. **空白**：全角空格 U+3000 / 不换行空格 U+00A0 / 连写空白 —— 折叠成单空格；
 *  4. **繁简**：`劉若英` ↔ `刘若英` —— 自建常用字表折叠（[HAN_FOLD_PAIRS]）。
 *
 * 折叠只作用于**去重键**，不作用于展示形态：胶囊上显示的是该实体出现次数最多的原始写法
 * （`刘若英` 不会被改写成别的字），点它搜索的也仍是这个原始词 —— 折叠不改搜索语义。
 *
 * 边界（诚实说明）：
 *  - 字表覆盖常用字（见 [HAN_FOLD_PAIRS]，逐条可在测试里枚举复核），**不保证全覆盖**；
 *    未覆盖的字按原样参与去重 —— 宁可漏合并一次，也不误合并两个不同实体；
 *  - 不做「一简对多繁」的反向还原（`干` 不会变 `乾/幹`），也不做拼音/近义归并。
 */
internal object SearchDiscovery {

    /** 展示形态清洗：NFKC + 折叠空白 + 剥两端标点引号（保留原大小写与简体/繁体写法）。 */
    fun clean(raw: String): String =
        Normalizer.normalize(raw, Normalizer.Form.NFKC)
            .let(::collapseSpaces)
            .trim { it.isWhitespace() || it in EDGE_PUNCT }

    /** 去重键：在 [clean] 之上再做小写折叠与繁→简折叠。 */
    fun dedupeKey(raw: String): String {
        val cleaned = clean(raw)
        if (cleaned.isEmpty()) return ""
        val lowered = cleaned.lowercase(Locale.ROOT)
        val sb = StringBuilder(lowered.length)
        lowered.forEach { c -> sb.append(HAN_FOLD[c] ?: c) }
        return sb.toString()
    }

    /** 占位符不是实体：「未知」/`<unknown>` 是标签缺失的兜底值，拿来当搜索发现是噪声。 */
    private val PLACEHOLDER_KEYS = setOf(
        "未知", "未知艺人", "未知专辑", "未知歌手", "unknown",
    )

    /** 键可用：非空、不是 `<...>` 这类占位、不在占位符表里。 */
    fun isUsableKey(key: String): Boolean =
        key.isNotEmpty() && !key.startsWith("<") && key !in PLACEHOLDER_KEYS

    /**
     * 取**本地曲库**高频艺人 / 专辑（spec §3.3 本地化口径，不造在线热搜）。
     *
     * 语义与旧实现一致：艺人取一半、专辑取一半，拼起来跨半区再去重、截到 [limit]。
     * 唯一差异是**去重按 [dedupeKey]**，同一实体的多写法合并后按合并计数排序 ——
     * 合并计数才不会让「繁体 3 首 + 简体 2 首」输给另一个只有 4 首的实体。
     */
    fun hotWords(tracks: List<Track>, limit: Int = 10): List<String> {
        if (tracks.isEmpty() || limit <= 0) return emptyList()
        val half = limit / 2
        val picked = topWords(tracks.map { it.artist }, half) +
            topWords(tracks.map { it.album }, half)
        val seen = HashSet<String>(picked.size * 2)
        val result = ArrayList<String>(limit)
        for (word in picked) {
            if (result.size >= limit) break
            // 跨半区去重：艺人名与专辑名撞名时只留先出现的那条（艺人半区优先）。
            if (seen.add(dedupeKey(word))) result += word
        }
        return result
    }

    private fun topWords(raw: List<String>, limit: Int): List<String> {
        if (limit <= 0) return emptyList()
        // key（去重键） -> （展示形态 -> 出现次数）
        val groups = LinkedHashMap<String, LinkedHashMap<String, Int>>()
        raw.forEach { word ->
            val key = dedupeKey(word)
            if (!isUsableKey(key)) return@forEach
            val display = clean(word)
            if (display.isEmpty()) return@forEach
            val forms = groups.getOrPut(key) { LinkedHashMap() }
            forms[display] = (forms[display] ?: 0) + 1
        }
        return groups.entries
            .sortedWith(
                compareByDescending<Map.Entry<String, LinkedHashMap<String, Int>>> { e ->
                    e.value.values.sum()
                }.thenBy { it.key },
            )
            .map { (_, forms) -> bestForm(forms) }
            .take(limit)
    }

    /**
     * 同一实体选哪个写法展示：出现次数最多的；次数相同取更短的（更「干净」，通常就是
     * 没有多余包裹的那条）；再相同取字典序，保证同一份曲库每次算出的结果完全一致。
     */
    private fun bestForm(forms: Map<String, Int>): String =
        forms.entries
            .sortedWith(
                compareByDescending<Map.Entry<String, Int>> { it.value }
                    .thenBy { it.key.length }
                    .thenBy { it.key },
            )
            .first()
            .key

    private fun collapseSpaces(s: String): String {
        val sb = StringBuilder(s.length)
        var pendingSpace = false
        s.forEach { c ->
            if (c.isWhitespace()) {
                pendingSpace = sb.isNotEmpty()
            } else {
                if (pendingSpace) sb.append(' ')
                pendingSpace = false
                sb.append(c)
            }
        }
        return sb.toString()
    }

